#!/usr/bin/env bash
set -euo pipefail

manifest=""
out_dir=""
allow_missing_validation=false
allow_failed_validation=false
allow_validation_bypasses=false
allow_missing_retry_pressure_fields=false
require_netem_evidence=true
required_retry_pressure_fields="undeliveredServerGbps,affectedUndeliveredServerGbps,affectedServerDatagramsOutPerSecond"

usage() {
  cat <<'USAGE'
Usage:
  benchmark/scripts/summarize-lab-impairment.sh --manifest manifest.jsonl [options]

Summarizes a completed host/NIC-level impairment campaign generated by
plan-lab-impairment.sh. The script reads each profile artifact root from the
campaign manifest, collects validation status, aggregate metrics, capacity
selections, and netem status evidence, then writes campaign-level outputs.

Options:
  --manifest PATH                  Impairment campaign manifest.jsonl. Required.
  --out DIR                        Output directory. Default: <manifest dir>/campaign-summary.
  --allow-missing-validation       Do not fail when a profile has no validation.json.
  --allow-failed-validation        Do not fail when a profile validation failed.
  --allow-validation-bypasses      Do not fail when profile validation used bypass flags. Smoke only.
  --allow-missing-retry-pressure-fields
                                     Do not fail when contention rows lack retry-pressure fields. Smoke only.
  --allow-missing-netem-evidence   Do not fail when profile status evidence is missing.
  --required-retry-pressure-fields CSV
                                    Required contention-row retry-pressure metric fields.
                                    Default: undeliveredServerGbps,affectedUndeliveredServerGbps,affectedServerDatagramsOutPerSecond.
  --help                           Show this help.

Outputs:
  impairment-summary.json          Machine-readable campaign summary.
  impairment-summary.jsonl         One machine-readable profile row per line.
  impairment-summary.md            Human-readable campaign report.
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --manifest)
      manifest="$2"
      shift 2
      ;;
    --out)
      out_dir="$2"
      shift 2
      ;;
    --allow-missing-validation)
      allow_missing_validation=true
      shift
      ;;
    --allow-failed-validation)
      allow_failed_validation=true
      shift
      ;;
    --allow-validation-bypasses)
      allow_validation_bypasses=true
      shift
      ;;
    --allow-missing-retry-pressure-fields)
      allow_missing_retry_pressure_fields=true
      shift
      ;;
    --allow-missing-netem-evidence)
      require_netem_evidence=false
      shift
      ;;
    --required-retry-pressure-fields)
      required_retry_pressure_fields="$2"
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ -z "$manifest" ]]; then
  usage >&2
  exit 2
fi
if ! command -v jq >/dev/null 2>&1; then
  echo "jq is required to summarize lab impairment campaigns" >&2
  exit 2
fi

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
if [[ "$manifest" != /* ]]; then
  manifest="$repo_root/$manifest"
fi
if [[ ! -s "$manifest" ]]; then
  echo "manifest not found or empty: $manifest" >&2
  exit 2
fi

manifest_dir="$(cd "$(dirname "$manifest")" && pwd)"
if [[ -z "$out_dir" ]]; then
  out_dir="$manifest_dir/campaign-summary"
elif [[ "$out_dir" != /* ]]; then
  out_dir="$repo_root/$out_dir"
fi
mkdir -p "$out_dir"

profile_jsonl="$out_dir/impairment-summary.jsonl"
summary_json="$out_dir/impairment-summary.json"
summary_md="$out_dir/impairment-summary.md"
work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT

empty_object="$work_dir/empty-object.json"
empty_array="$work_dir/empty-array.json"
printf '{}\n' >"$empty_object"
printf '[]\n' >"$empty_array"
: >"$profile_jsonl"

json_string_array() {
  if [[ "$#" -eq 0 ]]; then
    printf '[]\n'
  else
    printf '%s\n' "$@" | jq -R -s 'split("\n") | map(select(length > 0))'
  fi
}

resolve_path() {
  local value="$1"
  if [[ "$value" == /* ]]; then
    printf '%s\n' "$value"
  else
    printf '%s\n' "$repo_root/$value"
  fi
}

while IFS=$'\t' read -r profile latency jitter loss artifact_root netem_evidence_dir; do
  if [[ -z "$profile" ]]; then
    continue
  fi

  artifact_root_path="$(resolve_path "$artifact_root")"
  netem_evidence_path="$(resolve_path "$netem_evidence_dir")"
  validation_path="$artifact_root_path/combined/validation.json"
  aggregate_path="$artifact_root_path/combined/suite-aggregate.jsonl"
  capacity_path="$artifact_root_path/combined/bandwidth-capacity.jsonl"

  validation_exists=false
  validation_source="$empty_object"
  if [[ -s "$validation_path" ]]; then
    validation_exists=true
    validation_source="$validation_path"
  fi

  aggregate_exists=false
  aggregate_array="$work_dir/$profile-aggregate.json"
  if [[ -s "$aggregate_path" ]]; then
    aggregate_exists=true
    jq -s '.' "$aggregate_path" >"$aggregate_array"
  else
    cp "$empty_array" "$aggregate_array"
  fi

  capacity_exists=false
  capacity_array="$work_dir/$profile-capacity.json"
  if [[ -s "$capacity_path" ]]; then
    capacity_exists=true
    jq -s '.' "$capacity_path" >"$capacity_array"
  else
    cp "$empty_array" "$capacity_array"
  fi

  status_files=()
  if [[ -d "$netem_evidence_path" ]]; then
    while IFS= read -r -d '' status_file; do
      status_files+=("$status_file")
    done < <(find "$netem_evidence_path" -maxdepth 1 -type f -name "$profile-status-*.txt" -print0 2>/dev/null | sort -z)
  fi
  status_files_json="$(json_string_array "${status_files[@]}")"

  jq -c -n \
    --arg profile "$profile" \
    --arg latency "$latency" \
    --arg jitter "$jitter" \
    --arg loss "$loss" \
    --arg artifactRoot "$artifact_root_path" \
    --arg validationPath "$validation_path" \
    --arg aggregatePath "$aggregate_path" \
    --arg capacityPath "$capacity_path" \
    --arg netemEvidenceDir "$netem_evidence_path" \
    --argjson validationExists "$validation_exists" \
    --argjson aggregateExists "$aggregate_exists" \
    --argjson capacityExists "$capacity_exists" \
    --argjson statusEvidenceFiles "$status_files_json" \
    --slurpfile validation "$validation_source" \
    --slurpfile aggregate "$aggregate_array" \
    --slurpfile capacity "$capacity_array" '
    def n($value): ($value // 0) | tonumber;
    def scenario($row):
      if (($row.benchmarkName // "") | startswith("curve-")) then "curve"
      else ($row.benchmarkName // "unknown")
      end;
    def contention($row):
      (scenario($row) == "multi-client-fanout")
      or (scenario($row) == "fairness")
      or (scenario($row) == "disappearing-clients")
      or (scenario($row) == "batched-game-traffic")
      or (scenario($row) == "resource-pack-transfer");
    def stable_capacity($row):
      {
        case: ($row.case // null),
        payloadSize: ($row.payloadSize // null),
        reliability: ($row.reliability // null),
        packetLimit: ($row.packetLimit // null),
        globalPacketLimit: ($row.globalPacketLimit // null),
        selected: ($row.selected // false),
        selectedBenchmarkName: ($row.selectedCandidate.benchmarkName // null),
        selectedDeliveredGbps: ($row.selectedCandidate.deliveredGbps // null),
        selectedProbeRttP99Millis: ($row.selectedCandidate.probeRttP99Millis // null),
        bestObservedBenchmarkName: ($row.bestObservedCandidate.benchmarkName // null),
        bestObservedDeliveredGbps: ($row.bestObservedCandidate.deliveredGbps // null),
        bestObservedProbeRttP99Millis: ($row.bestObservedCandidate.probeRttP99Millis // null)
      };

    ($validation[0] // {}) as $validationObject |
    ($aggregate[0] // []) as $rows |
    ($capacity[0] // []) as $capacityRows |
    {
      profile: $profile,
      latency: $latency,
      jitter: $jitter,
      loss: $loss,
      artifactRoot: $artifactRoot,
      validation: {
        exists: $validationExists,
        path: (if $validationExists then $validationPath else null end),
        passed: (if $validationExists then ($validationObject.passed // false) else false end),
        bypassFlags: (
          if $validationExists then
            [
              ["allowUnstable", ($validationObject.allowUnstable // false)],
              ["allowDisconnects", ($validationObject.allowDisconnects // false)],
              ["allowMissingCapacity", ($validationObject.allowMissingCapacity // false)],
              ["allowUnselectedCapacity", ($validationObject.allowUnselectedCapacity // false)],
              ["allowMissingHostContext", ($validationObject.allowMissingHostContext // false)],
              ["allowMissingPrereqContext", ($validationObject.allowMissingPrereqContext // false)],
              ["allowLoosePrereqGates", ($validationObject.allowLoosePrereqGates // false)]
            ]
            | map(select(.[1] == true) | .[0])
          else [] end
        ),
        rowCount: ($validationObject.rowCount // null),
        capacityRowCount: ($validationObject.capacityRowCount // null),
        hostReportCount: ($validationObject.hostReportCount // null),
        distinctHostnameCount: ($validationObject.distinctHostnameCount // null),
        issueCount: (if $validationExists then (($validationObject.issues // []) | length) else null end)
      },
      aggregate: {
        exists: $aggregateExists,
        path: (if $aggregateExists then $aggregatePath else null end),
        rowCount: ($rows | length),
        scenarioCounts: (reduce $rows[] as $row ({}; .[scenario($row)] = ((.[scenario($row)] // 0) + 1))),
        deliveredGbpsByScenario: (
          $rows
          | group_by(scenario(.))
          | map({
              scenario: scenario(.[0]),
              rows: length,
              medianDeliveredGbps: ((map(n(.deliveredGbps)) | sort) as $values | if ($values | length) == 0 then 0 else $values[((($values | length) - 1) / 2 | floor)] end),
              maxDeliveredGbps: (map(n(.deliveredGbps)) | max // 0),
              maxProbeRttP99Millis: (map(n(.probeRttP99Millis)) | max // 0)
            })
        ),
        contentionRows: (
          $rows
          | map(select(contention(.)) | . as $row | ({
                case: ($row.case // null),
                benchmarkName: ($row.benchmarkName // null),
                clients: ($row.clients // null),
                payloadSize: ($row.payloadSize // null),
                reliability: ($row.reliability // null),
                batched: ($row.batched // false),
                batchIntervalMillis: ($row.batchIntervalMillis // null),
                logicalPacketsPerBatch: ($row.logicalPacketsPerBatch // null),
                batchGroups: ($row.batchGroups // null),
                packetLimit: ($row.packetLimit // null),
                globalPacketLimit: ($row.globalPacketLimit // null),
                configuredMaxQueuedBytes: ($row.configuredMaxQueuedBytes // null),
                targetClientMbps: ($row.targetClientMbps // null),
                disappearanceMode: ($row.disappearanceMode // null),
                deliveredGbps: ($row.deliveredGbps // null),
                probeRttP99Millis: ($row.probeRttP99Millis // null),
                healthyFairnessIndex: ($row.healthyFairnessIndex // null),
                healthySentToDeliveredBytesRatio: ($row.healthySentToDeliveredBytesRatio // null),
                affectedSentToDeliveredBytesRatio: ($row.affectedSentToDeliveredBytesRatio // null),
                maxQueuedBytes: ($row.maxQueuedBytes // null),
                unstable: ($row.unstable // false),
                unstableReasons: ($row.unstableReasons // [])
              }
              + (if $row | has("undeliveredServerGbps") then {undeliveredServerGbps: $row.undeliveredServerGbps} else {} end)
              + (if $row | has("healthyUndeliveredServerGbps") then {healthyUndeliveredServerGbps: $row.healthyUndeliveredServerGbps} else {} end)
              + (if $row | has("affectedUndeliveredServerGbps") then {affectedUndeliveredServerGbps: $row.affectedUndeliveredServerGbps} else {} end)
              + (if $row | has("serverDatagramsOutPerSecond") then {serverDatagramsOutPerSecond: $row.serverDatagramsOutPerSecond} else {} end)
              + (if $row | has("healthyServerDatagramsOutPerSecond") then {healthyServerDatagramsOutPerSecond: $row.healthyServerDatagramsOutPerSecond} else {} end)
              + (if $row | has("affectedServerDatagramsOutPerSecond") then {affectedServerDatagramsOutPerSecond: $row.affectedServerDatagramsOutPerSecond} else {} end)
              + (if $row | has("sentToDeliveredBytesRatio") then {sentToDeliveredBytesRatio: $row.sentToDeliveredBytesRatio} else {} end)))
        )
      },
      capacity: {
        exists: $capacityExists,
        path: (if $capacityExists then $capacityPath else null end),
        rowCount: ($capacityRows | length),
        selectedCount: ($capacityRows | map(select((.selected // false) == true)) | length),
        rows: ($capacityRows | map(stable_capacity(.)))
      },
      netem: {
        evidenceDir: $netemEvidenceDir,
        statusEvidenceCount: ($statusEvidenceFiles | length),
        statusEvidenceFiles: $statusEvidenceFiles
      }
    }
  ' >>"$profile_jsonl"
done < <(jq -r '[.profile, .latency, .jitter, .loss, .artifactRoot, .netemEvidenceDir] | @tsv' "$manifest")

allow_missing_validation_json=false
allow_failed_validation_json=false
allow_validation_bypasses_json=false
allow_missing_retry_pressure_fields_json=false
require_netem_evidence_json=false
"$allow_missing_validation" && allow_missing_validation_json=true
"$allow_failed_validation" && allow_failed_validation_json=true
"$allow_validation_bypasses" && allow_validation_bypasses_json=true
"$allow_missing_retry_pressure_fields" && allow_missing_retry_pressure_fields_json=true
"$require_netem_evidence" && require_netem_evidence_json=true
required_retry_pressure_fields_json="$(jq -cn --arg fields "$required_retry_pressure_fields" '
  $fields
  | split(",")
  | map(gsub("^\\s+|\\s+$"; ""))
  | map(select(length > 0))
')"

jq -s \
  --arg checkedAt "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
  --arg manifest "$manifest" \
  --arg outDir "$out_dir" \
  --argjson allowMissingValidation "$allow_missing_validation_json" \
  --argjson allowFailedValidation "$allow_failed_validation_json" \
  --argjson allowValidationBypasses "$allow_validation_bypasses_json" \
  --argjson allowMissingRetryPressureFields "$allow_missing_retry_pressure_fields_json" \
  --argjson requiredRetryPressureFields "$required_retry_pressure_fields_json" \
  --argjson requireNetemEvidence "$require_netem_evidence_json" '
  def issue($code; $message; $profile; $extra):
    {code:$code,message:$message,profile:$profile} + $extra;
  . as $profiles |
  (
    []
    + (if ($profiles | length) == 0 then
        [issue("missing-profiles"; "impairment campaign manifest produced no profile rows"; null; {})]
      else [] end)
    + ($profiles | map(select((.validation.exists | not) and ($allowMissingValidation | not)) | issue("missing-validation"; "profile is missing combined validation.json"; .profile; {artifactRoot:.artifactRoot})))
    + ($profiles | map(select(.validation.exists and (.validation.passed | not) and ($allowFailedValidation | not)) | issue("failed-validation"; "profile validation did not pass"; .profile; {validationPath:.validation.path, issueCount:.validation.issueCount})))
    + ($profiles | map(select(.validation.exists and ((.validation.bypassFlags // []) | length) > 0 and ($allowValidationBypasses | not)) | issue("validation-bypass-flags"; "profile validation used baseline bypass flags"; .profile; {validationPath:.validation.path, bypassFlags:.validation.bypassFlags})))
    + ($profiles | map(select(.aggregate.exists | not) | issue("missing-aggregate"; "profile is missing combined suite-aggregate.jsonl"; .profile; {artifactRoot:.artifactRoot})))
    + (if $allowMissingRetryPressureFields then [] else
        ($profiles
        | map(. as $profile
          | .aggregate.contentionRows[]? as $row
          | $requiredRetryPressureFields[] as $field
          | select(($row | has($field)) | not)
          | issue("missing-retry-pressure-field"; "contention row is missing a required retry-pressure field"; $profile.profile; {case:($row.case // null), benchmarkName:($row.benchmarkName // null), field:$field})))
      end)
    + ($profiles | map(select($requireNetemEvidence and (.netem.statusEvidenceCount == 0)) | issue("missing-netem-status-evidence"; "profile is missing netem status evidence"; .profile; {netemEvidenceDir:.netem.evidenceDir})))
  ) as $issues |
  {
    summaryKind: "raknet-lab-impairment-campaign",
    checkedAt: $checkedAt,
    manifest: $manifest,
    outDir: $outDir,
    profileCount: ($profiles | length),
    validationPassedCount: ($profiles | map(select(.validation.passed == true)) | length),
    aggregateRowCount: ($profiles | map(.aggregate.rowCount) | add // 0),
    capacityRowCount: ($profiles | map(.capacity.rowCount) | add // 0),
    netemStatusEvidenceCount: ($profiles | map(.netem.statusEvidenceCount) | add // 0),
    requireNetemEvidence: $requireNetemEvidence,
    allowMissingValidation: $allowMissingValidation,
    allowFailedValidation: $allowFailedValidation,
    allowValidationBypasses: $allowValidationBypasses,
    allowMissingRetryPressureFields: $allowMissingRetryPressureFields,
    requiredRetryPressureFields: $requiredRetryPressureFields,
    passed: (($issues | length) == 0),
    issues: $issues,
    profiles: $profiles
  }
' "$profile_jsonl" >"$summary_json"

{
  echo "# Lab Impairment Campaign Summary"
  echo
  echo "- Checked: \`$(jq -r '.checkedAt' "$summary_json")\`"
  echo "- Manifest: \`$manifest\`"
  echo "- Result: \`$(jq -r 'if .passed then "passed" else "failed" end' "$summary_json")\`"
  echo "- Profiles: \`$(jq -r '.profileCount' "$summary_json")\`"
  echo "- Validation passed: \`$(jq -r '.validationPassedCount' "$summary_json")\`"
  echo "- Aggregate rows: \`$(jq -r '.aggregateRowCount' "$summary_json")\`"
  echo "- Capacity rows: \`$(jq -r '.capacityRowCount' "$summary_json")\`"
  echo "- Netem status evidence files: \`$(jq -r '.netemStatusEvidenceCount' "$summary_json")\`"
  echo "- Required retry-pressure fields: \`$(jq -r '.requiredRetryPressureFields | join(",")' "$summary_json")\`"
  echo "- Allow missing retry-pressure fields: \`$(jq -r '.allowMissingRetryPressureFields' "$summary_json")\`"
  echo
  echo "## Profiles"
  echo
  echo "| Profile | Network | Validation | Rows | Capacity selected | Netem status | Max p99 ms | Max delivered Gbps |"
  echo "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |"
  jq -r '
    .profiles[]
    | [
        .profile,
        (.latency + "/" + .jitter + "/" + .loss),
        (if .validation.exists then (if .validation.passed then "passed" else "failed" end) else "missing" end),
        (.aggregate.rowCount | tostring),
        (.capacity.selectedCount | tostring),
        (.netem.statusEvidenceCount | tostring),
        (([.aggregate.deliveredGbpsByScenario[].maxProbeRttP99Millis] | max // 0) | tostring),
        (([.aggregate.deliveredGbpsByScenario[].maxDeliveredGbps] | max // 0) | tostring)
      ]
    | @tsv
  ' "$summary_json" | while IFS=$'\t' read -r profile network validation rows selected netem p99 gbps; do
    echo "| \`$profile\` | \`$network\` | \`$validation\` | $rows | $selected | $netem | $p99 | $gbps |"
  done
  echo
  echo "## Issues"
  echo
  if jq -e '.issues | length == 0' "$summary_json" >/dev/null; then
    echo "No issues found."
  else
    echo "| Code | Profile | Message |"
    echo "| --- | --- | --- |"
    jq -r '.issues[] | "| `\(.code)` | `\(.profile // "-")` | \(.message) |"' "$summary_json"
  fi
} >"$summary_md"

echo "Impairment summary JSON: $summary_json"
echo "Impairment summary JSONL: $profile_jsonl"
echo "Impairment summary report: $summary_md"

if jq -e '.passed == true' "$summary_json" >/dev/null; then
  exit 0
fi
exit 1
